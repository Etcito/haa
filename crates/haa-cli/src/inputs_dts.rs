//! `haa inputs` output (ARCHITECTURE §8): the TypeScript declarations of a patch's published inputs.

use haa_core::patch::{InputKind, Patch};

/// `osc-curve` becomes `OscCurve`.
fn pascal_case(id: &str) -> String {
    let mut out = String::new();
    for part in id.split(|c: char| !c.is_alphanumeric()) {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            out.extend(first.to_uppercase());
            out.push_str(chars.as_str());
        }
    }
    if out.is_empty() { "Patch".into() } else { out }
}

/// `osc-curve` becomes `OSC_CURVE`.
fn upper_snake(id: &str) -> String {
    let mut out = String::new();
    for c in id.chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c.to_ascii_uppercase());
        } else if !out.ends_with('_') {
            out.push('_');
        }
    }
    let out = out.trim_end_matches('_');
    if out.is_empty() {
        "PATCH".into()
    } else {
        out.into()
    }
}

/// A TypeScript single-quoted string literal.
fn quoted(value: &str) -> String {
    format!("'{}'", value.replace('\\', "\\\\").replace('\'', "\\'"))
}

/// The `haa inputs` text for a patch: `PInputs`, `PTrigger` and `P_PATCH_ID`.
pub fn inputs_dts(patch: &Patch, file_name: &str) -> String {
    let p = pascal_case(&patch.id);
    let mut out = format!("// Generated by haa inputs from {file_name}. Do not edit.\n");
    out.push_str(&format!("export interface {p}Inputs {{\n"));
    for input in &patch.inputs {
        match input.kind {
            InputKind::Continuous => {
                let doc = if input.unit.is_empty() {
                    format!("{}..{}, default {}", input.min, input.max, input.default)
                } else {
                    format!(
                        "{} {}..{}, default {}",
                        input.unit, input.min, input.max, input.default
                    )
                };
                out.push_str(&format!("  /** {doc} */\n  {}?: number;\n", input.name));
            }
            InputKind::Enum => {
                let union = if input.values.is_empty() {
                    "never".to_string()
                } else {
                    input
                        .values
                        .iter()
                        .map(|value| quoted(value))
                        .collect::<Vec<_>>()
                        .join(" | ")
                };
                out.push_str(&format!("  {}?: {union};\n", input.name));
            }
            InputKind::Trigger => {}
        }
    }
    out.push_str("}\n\n");

    let triggers: Vec<String> = patch
        .inputs
        .iter()
        .filter(|input| input.kind == InputKind::Trigger)
        .map(|input| quoted(&input.name))
        .collect();
    let union = if triggers.is_empty() {
        "never".to_string()
    } else {
        triggers.join(" | ")
    };
    out.push_str(&format!("export type {p}Trigger = {union};\n\n"));
    out.push_str(&format!(
        "export const {}_PATCH_ID = {};\n",
        upper_snake(&patch.id),
        quoted(&patch.id)
    ));
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn patch(json: &str) -> Patch {
        serde_json::from_str(json).unwrap()
    }

    #[test]
    fn declarations_match_the_expected_text() {
        let patch = patch(
            r#"{"haa":1,"id":"osc-curve","title":"Osc Curve",
                "inputs":[
                    {"name":"pitch","kind":"continuous","unit":"Hz","min":200,"max":1200,
                     "default":440,"smooth":0.05,"curve":"log"},
                    {"name":"waveform","kind":"enum","values":["sine","saw"]},
                    {"name":"fire","kind":"trigger"}],
                "graph":{"duration":2,"nodes":[]}}"#,
        );

        assert_eq!(
            inputs_dts(&patch, "osc-curve.json"),
            "// Generated by haa inputs from osc-curve.json. Do not edit.\n\
             export interface OscCurveInputs {\n\
             \x20 /** Hz 200..1200, default 440 */\n\
             \x20 pitch?: number;\n\
             \x20 waveform?: 'sine' | 'saw';\n\
             }\n\
             \n\
             export type OscCurveTrigger = 'fire';\n\
             \n\
             export const OSC_CURVE_PATCH_ID = 'osc-curve';\n"
        );
    }

    #[test]
    fn trigger_union_is_never_without_trigger_inputs() {
        let patch = patch(
            r#"{"haa":1,"id":"siren","title":"Siren",
                "inputs":[{"name":"pitch","kind":"continuous","unit":"Hz","min":200,
                           "max":1200,"default":440}],
                "graph":{"duration":2,"nodes":[]}}"#,
        );
        let text = inputs_dts(&patch, "siren.json");
        assert!(text.contains("export type SirenTrigger = never;\n"));
        assert!(text.contains("  /** Hz 200..1200, default 440 */\n  pitch?: number;\n"));
        assert!(text.contains("export const SIREN_PATCH_ID = 'siren';\n"));
    }
}
