// Bundles the JS host, emits declarations, and prepares their import specifiers.
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const PACKAGE = fileURLToPath(new URL('./', import.meta.url));
const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const DIST = join(PACKAGE, 'dist');
const TSC = join(ROOT, 'node_modules', 'typescript', 'bin', 'tsc');
const ENTRIES = [
  { entry: 'src/index.ts', outfile: 'dist/index.js', platform: 'browser' },
  { entry: 'src/offline.ts', outfile: 'dist/offline.js', platform: 'neutral' },
  {
    entry: 'src/worklet.ts', outfile: 'dist/worklet.js', platform: 'browser',
    banner: { js: '// @etcito/haa AudioWorklet processor. Generated by build.mjs. Do not edit.' },
  },
  { entry: 'src/node.ts', outfile: 'dist/node.js', platform: 'node' },
  {
    entry: 'src/cli.ts', outfile: 'dist/cli.js', platform: 'node',
    banner: { js: '#!/usr/bin/env node' },
  },
  { entry: 'src/bank.ts', outfile: 'dist/bank.js', platform: 'neutral' },
  { entry: 'src/arranger.ts', outfile: 'dist/arranger.js', platform: 'neutral' },
];

/** Every .d.ts file under dir. */
function declarations(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return declarations(path);
    return name.endsWith('.d.ts') ? [path] : [];
  });
}

/** Rewrites relative './x.ts' and '../x.ts' specifiers (import, export from, import()) to '.js'. */
export function rewriteDeclarationSpecifiers(text) {
  return text.replace(/(\bfrom\s+|\bimport\s*\(\s*|\bimport\s+)(['"])(\.{1,2}\/[^'"]+?)\.ts\2/g, '$1$2$3.js$2');
}

try {
  for (const { entry, ...options } of ENTRIES) {
    if (!existsSync(join(PACKAGE, entry))) {
      console.log(`[haa build] skip ${entry}`);
      continue;
    }
    await build({
      absWorkingDir: PACKAGE,
      entryPoints: [entry],
      bundle: true,
      format: 'esm',
      target: 'es2022',
      minify: false,
      sourcemap: false,
      legalComments: 'none',
      logLevel: 'silent',
      ...options,
    });
  }
  execFileSync(process.execPath, [TSC, '-p', 'packages/haa/tsconfig.json'], { stdio: 'inherit', cwd: ROOT });
  for (const file of declarations(DIST)) {
    const before = readFileSync(file, 'utf8');
    const after = rewriteDeclarationSpecifiers(before);
    if (after !== before) writeFileSync(file, after);
  }
  if (!existsSync(join(PACKAGE, 'pkg', 'haa.wasm'))) {
    console.warn('[haa build] warning: pkg/haa.wasm is missing; run npm run build from the repo root');
  }
} catch (error) {
  console.error(`[haa build] ${String(error instanceof Error ? error.message : error).replace(/\s*\r?\n\s*/g, ' ')}`);
  process.exit(1);
}
