// Demo build (demo module, node): bakes every built-in family into <out>/audio, copies the
// worklet bundle and the static page files, generates out/demo-src/panels.gen.ts, bundles
// demo/main.ts with esbuild and writes <out>/build.json (BuildInfo).
//
//   node scripts/build-demo.ts [--out out/demo]
import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'esbuild';
import { bake } from '../src/bake/bake.ts';
import { registerBuiltins } from '../src/registry/builtins.ts';
import { listFamilies } from '../src/registry/registry.ts';

/** Hashes of a demo build (out/demo/build.json), matched against committed browser results. */
export interface BuildInfo {
  mainSha256: string;
  workletSha256: string;
  manifestSha256: string;
}

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const OUT_ROOT = resolve(ROOT, 'out');
const SRC_DIR = resolve(OUT_ROOT, 'demo-src');
const PANELS_DIR = resolve(ROOT, 'demo/panels');

function sha256(file: string): string {
  return createHash('sha256').update(readFileSync(file)).digest('hex');
}

/** Resolves the output directory and refuses anything that is not strictly under out/. */
function checkedOut(out: string): string {
  const dir = resolve(ROOT, out);
  if (!dir.startsWith(OUT_ROOT + sep) || dir === SRC_DIR) throw new Error(`refusing to build into ${out}: not under out/`);
  return dir;
}

/** Source of out/demo-src/panels.gen.ts: every demo/panels/*.ts sorted by file name. */
function panelsSource(): string {
  const files = readdirSync(PANELS_DIR).filter((f) => f.endsWith('.ts')).sort();
  const lines = ['// Generated by scripts/build-demo.ts, do not edit.'];
  files.forEach((f, i) => {
    const rel = relative(SRC_DIR, join(PANELS_DIR, f)).split(sep).join('/');
    lines.push(`import * as P${i} from '${rel}';`);
  });
  lines.push('', `export const PANELS = [${files.map((_, i) => `P${i}.PANEL`).join(', ')}];`);
  lines.push('export default PANELS;', '');
  return lines.join('\n');
}

/** Builds the demo page into `out` (cleared first; must be under out/) and returns its hashes. */
export async function buildDemo(out: string): Promise<BuildInfo> {
  const dir = checkedOut(out);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });

  registerBuiltins();
  bake(listFamilies(), { outDir: join(dir, 'audio'), log: (line) => console.log(line) });

  copyFileSync(resolve(ROOT, 'worklet/haa-processors.js'), join(dir, 'haa-processors.js'));
  copyFileSync(resolve(ROOT, 'demo/index.html'), join(dir, 'index.html'));
  copyFileSync(resolve(ROOT, 'demo/nmc.gpu.json'), join(dir, 'nmc.gpu.json'));

  mkdirSync(SRC_DIR, { recursive: true });
  writeFileSync(join(SRC_DIR, 'panels.gen.ts'), panelsSource());

  await build({
    entryPoints: [resolve(ROOT, 'demo/main.ts')],
    absWorkingDir: ROOT,
    outfile: join(dir, 'main.js'),
    bundle: true,
    format: 'esm',
    target: 'es2022',
    minify: false,
    sourcemap: false,
    platform: 'browser',
    logLevel: 'silent',
  });

  const info: BuildInfo = {
    mainSha256: sha256(join(dir, 'main.js')),
    workletSha256: sha256(join(dir, 'haa-processors.js')),
    manifestSha256: sha256(join(dir, 'audio/manifest.json')),
  };
  writeFileSync(join(dir, 'build.json'), JSON.stringify(info, null, 2) + '\n');
  return info;
}

function parseOut(argv: readonly string[]): string {
  let out = 'out/demo';
  for (let i = 0; i < argv.length; i++) {
    const value = argv[i + 1];
    if (argv[i] !== '--out') throw new Error(`unknown argument ${argv[i]}`);
    if (value === undefined || value.startsWith('--')) throw new Error('missing value for --out');
    out = value;
    i++;
  }
  return out;
}

async function main(): Promise<void> {
  const t0 = performance.now();
  const info = await buildDemo(parseOut(process.argv.slice(2)));
  console.log(JSON.stringify(info));
  console.log(`elapsed ${((performance.now() - t0) / 1000).toFixed(2)} s`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((e: unknown) => {
    console.error(`[build-demo] ${e instanceof Error ? e.message : String(e)}`);
    process.exit(1);
  });
}
