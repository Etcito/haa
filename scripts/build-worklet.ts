// Builds worklet/haa-processors.js, the self-contained esbuild bundle of src/worklet/entry.ts.
// Usage: node scripts/build-worklet.ts [--check]
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const ENTRY = fileURLToPath(new URL('../src/worklet/entry.ts', import.meta.url));
const OUT_DIR = fileURLToPath(new URL('../worklet/', import.meta.url));
const OUT_FILE = fileURLToPath(new URL('../worklet/haa-processors.js', import.meta.url));
const BANNER =
  '// @etcito/haa prebuilt AudioWorklet processors. Generated by scripts/build-worklet.ts from src/worklet/entry.ts. Do not edit.';

/** Bundles the worklet entry in memory and returns the normalized file text. */
export async function buildWorkletText(): Promise<string> {
  const result = await build({
    entryPoints: [ENTRY],
    absWorkingDir: ROOT,
    bundle: true,
    format: 'esm',
    target: 'es2022',
    minify: false,
    legalComments: 'none',
    charset: 'utf8',
    banner: { js: BANNER },
    write: false,
    logLevel: 'silent',
  });
  const file = result.outputFiles[0];
  if (!file) throw new Error('esbuild produced no output');
  return file.text
    .replace(/\r\n?/g, '\n')
    .split('\n')
    .map((line) => line.replace(/[ \t]+$/, ''))
    .join('\n');
}

async function main(): Promise<void> {
  const text = await buildWorkletText();
  if (process.argv.includes('--check')) {
    let current: string | null = null;
    try {
      current = readFileSync(OUT_FILE, 'utf8');
    } catch {
      current = null;
    }
    if (current !== text) {
      console.error('[build-worklet] worklet/haa-processors.js is stale; run node scripts/build-worklet.ts');
      process.exit(1);
    }
    return;
  }
  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(OUT_FILE, text);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((e: unknown) => {
    console.error(`[build-worklet] ${e instanceof Error ? e.message : String(e)}`);
    process.exit(1);
  });
}
